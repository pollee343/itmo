package ru.itmo.serv1.service;

import jakarta.json.*;
import jakarta.json.stream.JsonParser;
import jakarta.ws.rs.BadRequestException;

import java.io.StringReader;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.time.format.DateTimeParseException;
import java.util.Set;

public class PersonValidation {
    private static final Set<String> COUNTRIES = Set.of("SPAIN", "CHINA", "VATICAN", "NORTH_KOREA");
    private static final Set<String> COLORS = Set.of("GREEN", "RED", "BLACK", "BLUE", "YELLOW", "WHITE", "BROWN");
    public static final Set<String> FIELDS = Set.of("id", "name", "coordinatesX", "coordinatesY", "creationDate", "height", "birthday", "weight", "nationality", "hairColor", "eyeColor", "locationX", "locationY", "locationName");

    public static JsonObject input(String body) {
        JsonObject object;
        try (JsonParser parser = Json.createParser(new StringReader(body == null ? "" : body))) {
            if (!parser.hasNext() || parser.next() != JsonParser.Event.START_OBJECT)
                throw bad("Request body must be a JSON object");
            object = parser.getObject();
            if (parser.hasNext()) throw bad("Request body must contain one JSON object");
        } catch (JsonException | IllegalStateException e) {
            throw bad("Request body must be a JSON object");
        }
        if (object.containsKey("id") || object.containsKey("creationDate")) {
            throw bad("id and creationDate are generated by the server");
        }
        JsonObjectBuilder result = Json.createObjectBuilder();
        for (String field : new String[]{"name", "height", "birthday", "weight", "nationality", "hairColor", "eyeColor"}) {
            JsonValue value = object.getOrDefault(field, JsonValue.NULL);
            boolean optional = field.equals("birthday") || field.equals("weight");
            if (value == JsonValue.NULL && !optional) throw bad(field + " is required");
            if (value != JsonValue.NULL) validateValue(field, value);
            result.add(field, value);
        }
        result.add("coordinates", nested(object.get("coordinates"), false));
        JsonValue location = object.getOrDefault("location", JsonValue.NULL);
        result.add("location", location == JsonValue.NULL ? JsonValue.NULL : nested(location, true));
        return result.build();
    }

    private static JsonObject nested(JsonValue value, boolean location) {
        if (value == null || value.getValueType() != JsonValue.ValueType.OBJECT)
            throw bad(location ? "location must be an object" : "coordinates is required and must be an object");
        JsonObject object = value.asJsonObject();
        JsonObjectBuilder result = Json.createObjectBuilder();
        for (String axis : new String[]{"x", "y"}) {
            JsonValue coordinate = object.get(axis);
            if (coordinate == null || coordinate.getValueType() != JsonValue.ValueType.NUMBER)
                throw bad(axis + " must be a number");
            JsonNumber number = (JsonNumber) coordinate;
            if ((location || axis.equals("y")) && !number.isIntegral()) throw bad(axis + " must be an integer");
            result.add(axis, coordinate);
        }
        if (location) {
            JsonValue name = object.getOrDefault("name", JsonValue.NULL);
            if (name != JsonValue.NULL) validateValue("locationName", name);
            result.add("name", name);
        }
        return result.build();
    }

    public static Object filter(String field, String text) {
        if (text == null) throw bad(field + " is required");
        if (text.equals("null") && Set.of("birthday", "weight")
                .contains(field)) return null;
        try {
            if (Set.of("id", "height", "weight", "coordinatesY", "locationX", "locationY", "coordinatesX")
                    .contains(field)) {
                BigDecimal number = new BigDecimal(text);
                validateValue(field, Json.createValue(number));
                return number;
            }
            validateValue(field, Json.createValue(text));
            if (field.equals("birthday")) return LocalDate.parse(text);
            if (field.equals("creationDate")) return OffsetDateTime.parse(text)
                    .toInstant();
            return text;
        } catch (NumberFormatException e) {
            throw bad(field + " must be a number");
        }
    }

    private static void validateValue(String field, JsonValue value) {
        if (Set.of("id", "height", "weight", "coordinatesY", "locationX", "locationY", "coordinatesX")
                .contains(field)) {
            if (value.getValueType() != JsonValue.ValueType.NUMBER) throw bad(field + " must be a number");
            JsonNumber number = (JsonNumber) value;
            if (!field.equals("coordinatesX") && !number.isIntegral()) throw bad(field + " must be an integer");
            if (Set.of("id", "height", "weight")
                    .contains(field) && number.bigDecimalValue()
                    .signum() <= 0) throw bad(field + " must be greater than 0");
            return;
        }
        if (value.getValueType() != JsonValue.ValueType.STRING) throw bad(field + " must be a string");
        String text = ((JsonString) value).getString();
        if (text.isEmpty()) throw bad(field + " must not be empty");
        if (field.equals("nationality") && !COUNTRIES.contains(text)) throw bad("Invalid nationality");
        if ((field.equals("hairColor") || field.equals("eyeColor")) && !COLORS.contains(text))
            throw bad("Invalid " + field);
        try {
            if (field.equals("birthday")) {
                if (!text.matches("[0-9]{4}-[0-9]{2}-[0-9]{2}")) throw bad("birthday must have format yyyy-MM-dd");
                LocalDate.parse(text);
            }
            if (field.equals("creationDate")) {
                if (!text.matches("[0-9]{4}-[0-9]{2}-[0-9]{2}[Tt][0-9]{2}:[0-9]{2}:[0-9]{2}(\\.[0-9]+)?([Zz]|[+-][0-9]{2}:[0-9]{2})")) {
                    throw bad("creationDate must be an RFC 3339 date-time with a timezone");
                }
                OffsetDateTime.parse(text);
            }
        } catch (DateTimeParseException e) {
            throw bad("Invalid " + field);
        }
    }

    public static BadRequestException bad(String message) {
        return new BadRequestException(message);
    }
}
